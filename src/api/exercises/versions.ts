// ── Normalize ──────────────────────────────────────────────────────────────────

export function normalizeCheck(raw: CheckDTO | null | undefined): CheckDTO {
  if (raw?.Answer) {
    const { Type, Values, InputHint, IgnoreCase, Trim } = raw.Answer
    return { Answer: { Type, Values: Values ?? [], InputHint: InputHint ?? "", IgnoreCase: IgnoreCase ?? false, Trim: Trim ?? null } }
  }
  if (raw?.State) {
    const state: StateCheckDTO = { Mode: raw.State.Mode ?? "once", Interval: raw.State.Interval ?? "", Manual: raw.State.Manual ?? false, Conditions: (raw.State.Conditions ?? []) as ConditionDTO[] }
    return { State: state }
  }
  return {}
}

function normalizeTask(raw: TaskDTO): NormalizedTask {
  return {
    ID: raw.ID ?? "",
    Key: raw.Key ?? "",
    Name: raw.Name,
    Description: raw.Description ?? null,
    Difficulty: raw.Difficulty,
    Requires: raw.Requires ?? [],
    Check: normalizeCheck(raw.Check),
    Attachments: raw.Attachments ?? [],
    Placeholders: raw.Placeholders ?? [],
    Hints: (raw.Hints ?? []).map((hint) => ({ ID: hint.ID ?? "", Text: hint.Text ?? "", Level: HINT_LEVELS.includes(hint.Level) ? hint.Level : "nudge" })),
  }
}

function normalizeInterface(raw: InterfaceDTO): NormalizedInterface {
  return {
    Name: raw.Name,
    MAC: raw.MAC ?? "",
    IP: {
      Type: raw.IP?.Type ?? "none",
      Addresses: raw.IP?.Addresses ?? [],
      AddressRef: raw.IP?.AddressRef ?? null,
      Gateway: raw.IP?.Gateway ?? "",
      GatewayRef: raw.IP?.GatewayRef ?? null,
      Routes: (raw.IP?.Routes ?? []).map((route) => ({
        Dst: route.Dst ?? "", DstRef: route.DstRef ?? null,
        Via: route.Via ?? "", ViaRef: route.ViaRef ?? null,
      })),
    },
  }
}

function normalizeEnvVar(ev: EnvVarDTO): NormalizedEnvVar {
  return {
    Name: ev.Name,
    Value: ev.Value ?? "",
    Secret: ev.Secret,
    HasValue: ev.HasValue ?? false,
    ...(ev.Secret && typeof ev.ValueGroup === "number" && ev.ValueGroup > 0 ? { ValueGroup: ev.ValueGroup } : {}),
  }
}

function normalizeDevice(raw: DeviceDTO): NormalizedDevice {
  // The former value «container» is read as a node with the container profile.
  return {
    ID: raw.ID ?? "",
    Name: raw.Name,
    Type: raw.Type === "container" ? "node" : raw.Type,
    Profile: raw.Profile ?? "container",
    SecurityPreset: raw.SecurityPreset ?? "",
    Image: raw.Image ?? "",
    ResourcePreset: raw.ResourcePreset ?? "",
    Interfaces: (raw.Interfaces ?? []).map(normalizeInterface),
    Access: (raw.Access ?? []).map((entry) => ({ ...entry })),
    Command: raw.Command ?? [],
    Args: raw.Args ?? [],
    System: raw.System ?? "linux",
    Hardware: raw.Hardware ?? "fast",
    Bootstrap: {
      Timeout: raw.Bootstrap?.Timeout ?? "",
      Env: (raw.Bootstrap?.Env ?? []).map(normalizeEnvVar),
      Files: (raw.Bootstrap?.Files ?? []).map((file) => ({ ...file, Content: file.Content ?? "", Owner: file.Owner ?? "", Group: file.Group ?? "", Mode: file.Mode ?? "" })),
      Script: raw.Bootstrap?.Script ?? "",
      Interpreter: raw.Bootstrap?.Interpreter ?? "",
    },
    Persistence: raw.Persistence?.Enabled ? { Enabled: true, Debounce: raw.Persistence.Debounce ?? "" } : null,
    WaitReadyFile: raw.WaitReadyFile ?? false,
    DHCP: raw.DHCP ?? false,
    DHCPRanges: (raw.DHCPRanges ?? []).map(({ Start, End }) => ({ Start, End })),
    DNS: raw.DNS ?? "",
    ReverseConnections: raw.ReverseConnections ?? false,
  }
}

export function normalizeTopology(raw: TopologyDTO | null | undefined): NormalizedTopology {
  return {
    Variables: (raw?.Variables ?? []).map((variable) => ({ Name: variable.Name, ...(variable.Template ? { Template: variable.Template } : { Value: variable.Value ?? "" }) })),
    Devices: (raw?.Devices ?? []).map(normalizeDevice),
    Connections: (raw?.Connections ?? []).map((c) => ({
      Endpoints: (c.Endpoints ?? []).map((ep) => ({
        Kind: ep.Kind,
        DeviceID: ep.DeviceID ?? "",
        Interface: ep.Interface ?? "",
      })),
    })),
    VisualRender: raw?.VisualRender ?? null,
  }
}

export function normalizeVariant(raw: VariantDTO): NormalizedVariant {
  return {
    ID: raw.ID ?? "",
    Index: raw.Index,
    Note: raw.Note ?? "",
    Weight: normalizeWeight(raw.Weight),
    LinkedTo: raw.LinkedTo ?? "",
    ImageOverrides: raw.LinkedTo ? (raw.ImageOverrides ?? []).map(({ DeviceID, Image }) => ({ DeviceID, Image })) : [],
    Tasks: (raw.Tasks ?? []).map(normalizeTask),
    Topology: normalizeTopology(raw.Topology),
  }
}

type RawVersion = Omit<Version, "Variants" | "Label" | "Resources" | "Elevation" | "Tags"> & {
  Variants: VariantDTO[] | null
  Tags?: string[] | null
  Label?: string
  Resources?: (Omit<VersionResources, "Outside" | "Variants"> & { Outside: DeviceOutside[] | null; Variants: VersionResources["Variants"] | null }) | null
  Elevation?: Parameters<typeof normalizeElevation>[0] | null
}

export function normalizeResources(raw: RawVersion["Resources"]): VersionResources | null {
  return raw ? { ...raw, Outside: raw.Outside ?? [], Variants: raw.Variants ?? [] } : null
}

function normalizeVersion(raw: RawVersion): Version {
  return {
    ...raw,
    Name: raw.Name, Description: raw.Description, Tags: raw.Tags === undefined ? undefined : [...(raw.Tags ?? [])],
    Label: raw.Label ?? "", Variants: (raw.Variants ?? []).map(normalizeVariant),
    Resources: normalizeResources(raw.Resources), Elevation: raw.Elevation ? normalizeElevation(raw.Elevation) : null,
  }
}

// ── API ────────────────────────────────────────────────────────────────────────

/** GET /api/exercises/:id/versions */
export async function listVersions(exerciseId: string): Promise<VersionListItem[]> {
  const raw = await apiGet<(Omit<VersionListItem, "Label"> & { Label?: string })[] | null>(`${BASE}/${exerciseId}/versions`)
  return (raw ?? []).map((item) => ({ ...item, Label: item.Label ?? "" }))
}

/** GET /api/exercises/:id/versions/:versionID */
export async function getVersion(exerciseId: string, versionId: string): Promise<Version> {
  const raw = await apiGet<RawVersion>(`${BASE}/${exerciseId}/versions/${versionId}`)
  return normalizeVersion(raw)
}

/** PUT /api/exercises/:id/draft — full snapshot */
export async function saveDraft(exerciseId: string, input: SaveDraftInput): Promise<Version> {
  const raw = await apiPut<RawVersion>(`${BASE}/${exerciseId}/draft`, input)
  return normalizeVersion(raw)
}

/** POST /api/exercises/:id/publish */
export async function publishDraft(exerciseId: string): Promise<Version> {
  const raw = await apiPost<RawVersion>(`${BASE}/${exerciseId}/publish`, {})
  return normalizeVersion(raw)
}

/** ID of the empty working copy (no draft row, nothing published). Never used in version routes. */
export const EMPTY_VERSION_ID = "00000000-0000-0000-0000-000000000000"

export function isStoredVersionId(id: string): boolean {
  return id !== "" && id !== EMPTY_VERSION_ID
}

/** GET /api/exercises/:id/draft — the working copy (published content when no draft row exists). */
export async function getDraft(exerciseId: string): Promise<Version> {
  return normalizeVersion(await apiGet<RawVersion>(`${BASE}/${exerciseId}/draft`))
}

/** PUT /api/exercises/:id/draft with keepalive — only for pagehide. */
export function saveDraftKeepalive(exerciseId: string, input: SaveDraftInput): boolean {
  return apiKeepalive("PUT", `${BASE}/${exerciseId}/draft`, input)
}

/** POST /api/exercises/:id/checkpoints — snapshot of the working copy with an optional caption (≤ 500). */
export async function createCheckpoint(exerciseId: string, note = ""): Promise<Version> {
  const trimmed = note.trim()
  const raw = await apiPost<RawVersion>(`${BASE}/${exerciseId}/checkpoints`, trimmed ? { Note: trimmed } : {})
  return normalizeVersion(raw)
}

/** POST /api/exercises/:id/versions/:versionID/restore — preserves the current draft. */
export async function restoreVersion(exerciseId: string, versionId: string): Promise<Version> {
  const raw = await apiPost<RawVersion>(`${BASE}/${exerciseId}/versions/${versionId}/restore`, {})
  return normalizeVersion(raw)
}
